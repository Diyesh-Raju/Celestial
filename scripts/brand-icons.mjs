// Generates the brand icons from the mark in src/lib/logo.ts:
//   src/app/icon.svg    tab favicon; burgundy, switching to rose when the OS is in dark mode
//   src/app/icon1.png   192px PNG favicon, the raster icon Google Search shows beside results
//   public/favicon.ico  16/32/48px, for crawlers and browsers that only ask for /favicon.ico
//   public/logo.png     512px logo referenced by the Organization structured data
// Deterministic, so re-running it reproduces the committed files.
// usage: node scripts/brand-icons.mjs
import { writeFile } from "node:fs/promises";
import sharp from "sharp";
import { LOGO_PATH } from "../src/lib/logo.ts";

const root = new URL("..", import.meta.url).pathname;
const BURGUNDY = "#561226";
const ROSE = "#c4798b";
// The mark spans 4–44 of its 48 box; favicons crop to it (with a hair of room for
// anti-aliasing) so it fills the tab, the logo keeps the full box as padding
const CROP = "3.5 3.5 41 41";

const markSvg = (size, viewBox) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${viewBox}">` +
  `<path fill="${BURGUNDY}" d="${LOGO_PATH}"/></svg>`;

const png = (size, viewBox = CROP) =>
  sharp(Buffer.from(markSvg(size, viewBox))).png({ compressionLevel: 9 }).toBuffer();

/** An .ico holding PNG-encoded images (supported by every current browser and Windows) */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size, e); // width
    header.writeUInt8(size, e + 1); // height
    header.writeUInt16LE(1, e + 4); // colour planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((im) => im.data)]);
}

// The fill attribute is the fallback for renderers that skip <style>
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${CROP}">
  <!-- Generated by scripts/brand-icons.mjs from src/lib/logo.ts. The bare burgundy mark,
       no tile, cropped so it fills the tab icon. Burgundy disappears on dark tab strips, so
       it switches to the brand rose when the OS is in dark mode (a favicon's
       prefers-color-scheme follows the OS, not the browser theme). -->
  <style>
    @media (prefers-color-scheme: dark) {
      path { fill: ${ROSE}; }
    }
  </style>
  <path fill="${BURGUNDY}" d="${LOGO_PATH}"/>
</svg>
`;

const icoSizes = [16, 32, 48];
const icoImages = await Promise.all(icoSizes.map(async (size) => ({ size, data: await png(size) })));

await writeFile(`${root}src/app/icon.svg`, iconSvg);
await writeFile(`${root}src/app/icon1.png`, await png(192));
await writeFile(`${root}public/favicon.ico`, ico(icoImages));
await writeFile(`${root}public/logo.png`, await png(512, "0 0 48 48"));
console.log("wrote icon.svg, icon1.png, favicon.ico, logo.png");
